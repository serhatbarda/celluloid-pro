#!/usr/bin/env python3
"""Self-test of the headless OFX host against the OpenFX SDK example plug-ins.

Checks numeric correctness of renders (exact or quantisation-bounded), every
parameter type the CLI can set, push buttons / messages, plug-in initiated
keyframes during instanceChanged, render scale, multi-frame renders, keyframe
interpolation, batch mode, pixel depth negotiation, the OpenCL buffer and image
render paths (CPU vs GPU bit-exactness), the embedded PNG writer, error exit
codes and strict protocol checking.

usage: test_sdk_plugins.py --host ofxhost --bundles DIR --work DIR [--opencl 1]
"""
import argparse
import json
import os
import struct
import subprocess
import sys
import zlib

import numpy as np
from PIL import Image

W, H = 96, 64
RESULTS = []


def run(host, args, expect=0, check=True):
    cmd = [host] + args
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if check and p.returncode != expect:
        raise AssertionError("exit %d (expected %d): %s\nstdout:\n%s\nstderr:\n%s"
                             % (p.returncode, expect, " ".join(cmd), p.stdout, p.stderr))
    return p


def load(path, w=W, h=H):
    a = np.fromfile(path, dtype="<f4")
    assert a.size == w * h * 4, "%s: %d floats, expected %d" % (path, a.size, w * h * 4)
    return a.reshape(h, w, 4)


def gradient(w=W, h=H):
    """pattern:gradient as generated by the host (top-down rows)."""
    img = np.zeros((h, w, 4), np.float32)
    x = (np.arange(w, dtype=np.float32) / np.float32(w - 1))[None, :]
    y = (np.arange(h, dtype=np.float32) / np.float32(h - 1))[:, None]
    img[..., 0] = x
    img[..., 1] = y
    img[..., 2] = 0.5
    img[..., 3] = np.float32(0.25) + np.float32(0.75) * x
    return img


def decode_png(path):
    """Independent PNG decoder (zlib + unfiltering) used to verify the host's writer bit-exactly."""
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    pos, idat, hdr = 8, b"", None
    while pos < len(data):
        n, = struct.unpack(">I", data[pos:pos + 4])
        typ = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + n]
        crc, = struct.unpack(">I", data[pos + 8 + n:pos + 12 + n])
        assert zlib.crc32(typ + body) & 0xffffffff == crc, "bad CRC in " + typ.decode()
        if typ == b"IHDR":
            hdr = struct.unpack(">IIBBBBB", body)
        elif typ == b"IDAT":
            idat += body
        pos += 12 + n
    w, h, depth, ctype = hdr[0], hdr[1], hdr[2], hdr[3]
    ch = {2: 3, 6: 4}[ctype]
    bpp = ch * depth // 8
    raw = zlib.decompress(idat)
    stride = w * bpp
    out = bytearray(h * stride)
    prev = bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b_ = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b_) & 255
            elif f == 3: line[i] = (line[i] + (a + b_) // 2) & 255
            elif f == 4:
                pp = a + b_ - c
                pa, pb, pc = abs(pp - a), abs(pp - b_), abs(pp - c)
                pr = a if (pa <= pb and pa <= pc) else (b_ if pb <= pc else c)
                line[i] = (line[i] + pr) & 255
        out[y * stride:(y + 1) * stride] = line
        prev = line
    arr = np.frombuffer(bytes(out), dtype=np.uint8 if depth == 8 else ">u2")
    return arr.reshape(h, w, ch)


def quant(x, m):
    """PNG quantisation convention of the host: floor(clamp(v,0,1) * m + 0.5) in double."""
    x = np.nan_to_num(x.astype(np.float64), nan=0.0)
    return np.floor(np.clip(x, 0.0, 1.0) * m + 0.5)


def check(name, cond, detail=""):
    RESULTS.append((name, bool(cond), detail))
    print("%-58s %s %s" % (name, "PASS" if cond else "FAIL", detail))


def maxdiff(a, b):
    return float(np.max(np.abs(a.astype(np.float64) - b.astype(np.float64))))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", required=True)
    ap.add_argument("--bundles", required=True)
    ap.add_argument("--work", required=True)
    ap.add_argument("--opencl", default="1")
    a = ap.parse_args()
    host, B, Wd = a.host, a.bundles, a.work
    have_cl = a.opencl in ("1", "ON", "TRUE", "true", "on")
    os.makedirs(Wd, exist_ok=True)
    b = lambda n: os.path.join(B, n + ".ofx.bundle")
    o = lambda n: os.path.join(Wd, n)
    size = ["--width", str(W), "--height", str(H)]
    grad = gradient()

    # ---- C API Invert (8-bit only plug-in; host frame threading path) -------------------
    run(host, [b("sdk_invert"), "--in", "pattern:gradient"] + size + ["--out", o("inv_c"), "--strict"])
    q = np.round(np.clip(grad, 0, 1) * 255.0)
    exp = (255.0 - q) / 255.0
    d = maxdiff(load(o("inv_c.f32")), exp)
    check("C-API Invert (byte depth, frame threading) exact", d < 1e-6, "maxdiff=%.3g" % d)

    # ---- C API Basic gain, float + short via depth negotiation --------------------------
    run(host, [b("sdk_basic"), "--in", "pattern:gradient"] + size + ["--set", "scale=0.5", "--out", o("basic_c"), "--strict"])
    d = maxdiff(load(o("basic_c.f32")), grad * np.float32(0.5))
    check("C-API Basic gain=0.5 float", d < 1e-6, "maxdiff=%.3g" % d)
    run(host, [b("sdk_basic"), "--in", "pattern:gradient"] + size +
        ["--depths", "short,byte", "--set", "scale=0.5", "--out", o("basic_c16"), "--report", o("basic_c16.json")])
    rep = json.load(open(o("basic_c16.json")))
    chosen = {c["name"]: c.get("chosen", "") for c in rep["clips"]}
    exp16 = np.floor(np.round(np.clip(grad, 0, 1) * 65535) * 0.5) / 65535.0
    d = maxdiff(load(o("basic_c16.f32")), exp16)
    check("C-API Basic 16-bit depth negotiation", "Short" in chosen.get("Output", "") and d < 1.6e-5,
          "chosen=%s maxdiff=%.3g" % (chosen.get("Output"), d))
    run(host, [b("sdk_basic"), "--in", "pattern:gradient"] + size +
        ["--set", "scaleComponents=true", "--set", "scaleR=2", "--set", "scaleA=0.5", "--out", o("basic_c2")])
    exp = grad * np.array([2, 1, 1, 0.5], np.float32)
    d = maxdiff(load(o("basic_c2.f32")), exp)
    check("C-API Basic per-component (bool + doubles)", d < 1e-6, "maxdiff=%.3g" % d)

    # ---- Support library Invert (float) from a raw .f32 file ----------------------------
    rng = np.random.default_rng(7)
    rnd = rng.uniform(-0.5, 2.0, (H, W, 4)).astype("<f4")
    rnd.tofile(o("rand_in.f32"))
    run(host, [b("sdks_invert"), "--in", o("rand_in.f32")] + size + ["--out", o("inv_s"), "--strict"])
    d = maxdiff(load(o("inv_s.f32")), 1.0 - rnd)
    check("Support Invert float from .f32 (orientation, exact)", d == 0.0, "maxdiff=%.3g" % d)

    # ---- Support Basic gain ---------------------------------------------------------------
    run(host, [b("sdks_basic"), "--in", "pattern:gradient"] + size +
        ["--set", "scale=2", "--set", "scaleG=0.25", "--set", "scaleA=0.5", "--out", o("basic_s"), "--strict"])
    exp = grad * np.array([2, 0.5, 2, 0.5], np.float32)
    d = maxdiff(load(o("basic_s.f32")), exp)
    check("Support Basic gain (scale * component)", d < 1e-6, "maxdiff=%.3g" % d)

    # ---- ChoiceParams: Choice by label / index, StrChoice by enum / label -----------------
    run(host, [b("sdks_choiceparams"), "--in", "pattern:white"] + size +
        ["--set", "red_choice=label:red: some", "--set", "green_choice=1", "--set", "blue_choice=blue_0.5",
         "--out", o("choice1"), "--strict"])
    px = load(o("choice1.f32"))[0, 0]
    check("Choice by label/index + StrChoice by enum", np.allclose(px, [0.5, 1.0, 0.5, 1.0]), str(px))
    run(host, [b("sdks_choiceparams"), "--in", "pattern:white"] + size +
        ["--set", "red_choice=lots", "--set", "green_choice=green: some", "--set", "blue_choice=blue: lots",
         "--out", o("choice2")])
    px = load(o("choice2.f32"))[0, 0]
    check("Choice/StrChoice by unique label substring", np.allclose(px, [1.0, 0.5, 1.0, 1.0]), str(px))
    p = run(host, [b("sdks_choiceparams"), "--in", "pattern:white"] + size + ["--set", "red_choice=purple", "--render"], expect=2)
    check("bad choice label -> exit 2", "neither a valid index" in p.stderr, p.stderr.strip().splitlines()[-1][:80])

    # ---- Tester: push button message, analysis (plug-in keyframes + clipGetImage outside render)
    run(host, [b("sdks_tester"), "--in", "pattern:gradient"] + size +
        ["--frames", "0:5", "--press", "pbButton", "--press", "analyseButton", "--set", "enableTest=1",
         "--set", "widgetPos=0.25,0.75", "--set", "angleTest=45", "--list-params-json", o("tester_params.json"),
         "--report", o("tester.json"), "--out", o("tester")])
    rep = json.load(open(o("tester.json")))
    msgs = [m["text"] for m in rep["messages"]]
    check("push button -> instanceChanged -> sendMessage", any("TestPassed" in m for m in msgs), str(msgs[:2]))
    prm = {p["name"]: p for p in json.load(open(o("tester_params.json")))["params"]}
    keys = prm["analysisParam"]["keys"]
    log = rep["instanceChangedLog"]
    plug_edits = [l for l in log if l.startswith("OfxChangePluginEdited:param:analysisParam")]
    check("analysis: plug-in set 5 keyframes, host notified (pluginEdited)", keys == 5 and len(plug_edits) == 5,
          "keys=%d notifications=%d" % (keys, len(plug_edits)))
    check("plug-in disabled param via instanceChanged", prm["enableDbl"]["enabled"] is False)
    check("Double2D set (a,b)", prm["widgetPos"]["value"] == [0.25, 0.75], str(prm["widgetPos"]["value"]))
    check("render over 6 frames writes 6 outputs", all(os.path.exists(o("tester.%04d.f32" % t)) for t in range(6)))
    check("secret param flagged in JSON", prm["secretTest"]["secret"] is True)

    # ---- GPU Gain: CPU, OpenCL buffers, OpenCL images --------------------------------------
    gain = ["--set", "scale=2", "--set", "scaleG=0.5", "--set", "scaleA=0.75"]
    exp = grad * np.array([2, 1, 2, 0.75], np.float32)
    run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + gain + ["--out", o("gg_cpu"), "--strict"])
    cpu = load(o("gg_cpu.f32"))
    d = maxdiff(cpu, exp)
    check("GPUGain CPU numeric", d < 1e-6, "maxdiff=%.3g" % d)
    if have_cl:
        run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + gain +
            ["--gpu", "opencl", "--out", o("gg_clb"), "--report", o("gg_clb.json"), "--strict"])
        rep = json.load(open(o("gg_clb.json")))
        fr = rep["jobs"][0]["frames"][0]
        d = maxdiff(load(o("gg_clb.f32")), cpu)
        check("GPUGain OpenCL buffers == CPU (bit exact)", d == 0.0 and fr["gpu"] == "opencl-buffers",
              "maxdiff=%.3g gpu=%s" % (d, fr["gpu"]))
        run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + gain +
            ["--gpu", "opencl-images", "--out", o("gg_cli"), "--strict"])
        d = maxdiff(load(o("gg_cli.f32")), cpu)
        check("GPUGain OpenCL images == CPU (bit exact)", d == 0.0, "maxdiff=%.3g" % d)
        run(host, [b("sdks_gpugain"), "--in", "pattern:noise:5"] + size + gain +
            ["--gpu", "opencl", "--frames", "0:2", "--render-scale", "0.5", "--out", o("gg_clseq")])
        run(host, [b("sdks_gpugain"), "--in", "pattern:noise:5"] + size + gain +
            ["--frames", "0:2", "--render-scale", "0.5", "--out", o("gg_cpuseq")])
        d = max(maxdiff(load(o("gg_clseq.%04d.f32" % t), W // 2, H // 2), load(o("gg_cpuseq.%04d.f32" % t), W // 2, H // 2))
                for t in range(3))
        check("OpenCL multi-frame + render scale 0.5 == CPU", d == 0.0, "maxdiff=%.3g" % d)
        p = run(host, [b("sdks_invert"), "--in", "pattern:gradient"] + size + ["--gpu", "opencl", "--render"], expect=1)
        check("--gpu on a CPU-only plug-in fails cleanly", "does not declare OpenCL" in p.stderr)
        run(host, [b("sdks_invert"), "--in", "pattern:gradient"] + size + ["--gpu", "opencl", "--gpu-fallback", "--out", o("inv_fb")])
        d = maxdiff(load(o("inv_fb.f32")), 1.0 - grad)
        check("--gpu-fallback renders on CPU", d == 0.0)

    # ---- identity ------------------------------------------------------------------------
    run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + ["--out", o("gg_id"), "--report", o("gg_id.json")])
    fr = json.load(open(o("gg_id.json")))["jobs"][0]["frames"][0]
    d = maxdiff(load(o("gg_id.f32")), grad)
    check("isIdentity honoured (pass-through)", fr["identity"] and d == 0.0, "identity=%s" % fr["identity"])

    # ---- render scale 0.5 ------------------------------------------------------------------
    run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + gain +
        ["--render-scale", "0.5", "--out", o("gg_half"), "--report", o("gg_half.json")])
    half = load(o("gg_half.f32"), W // 2, H // 2)
    ds = grad.reshape(H // 2, 2, W // 2, 2, 4).mean(axis=(1, 3))
    d = maxdiff(half, ds * np.array([2, 1, 2, 0.75], np.float32))
    fr = json.load(open(o("gg_half.json")))["jobs"][0]["frames"][0]
    check("render scale 0.5: size + area-downsampled source", (fr["width"], fr["height"]) == (W // 2, H // 2) and d < 1e-6,
          "maxdiff=%.3g" % d)

    # ---- keyframes + multi-frame -------------------------------------------------------------
    run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size +
        ["--set", "scale@0=1", "--set", "scale@10=3", "--frames", "0:10:5", "--out", o("gg_key"), "--report", o("gg_key.json")])
    ok = True
    det = []
    for t, g in ((0, 1.0), (5, 2.0), (10, 3.0)):
        img = load(o("gg_key.%04d.f32" % t))
        e = grad * np.array([g, g, g, 1], np.float32)
        dd = maxdiff(img, e)
        det.append("t%d:%.2g" % (t, dd))
        ok = ok and dd < 1e-6
    check("keyframed param interpolated per frame (1 -> 2 -> 3)", ok, " ".join(det))

    run(host, [b("sdks_invert"), "--in", "pattern:noise:3"] + size + ["--frames", "0:2", "--out", o("noise")])
    f0, f1 = load(o("noise.0000.f32")), load(o("noise.0001.f32"))
    check("time-varying input pattern per frame", maxdiff(f0, f1) > 0.1)

    # ---- repeatability: same render twice is bit-identical ------------------------------------
    run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + gain + ["--out", o("gg_cpu2")])
    check("repeatable renders (bit identical)", maxdiff(load(o("gg_cpu2.f32")), cpu) == 0.0)

    # ---- batch mode on one instance ---------------------------------------------------------
    with open(o("batch.txt"), "w") as f:
        f.write("# comment line\n")
        f.write("--set scale=2 --out %s --label two\n" % o("bt_a"))
        f.write("--set scaleR=0.5 --out %s\n" % o("bt_b"))
        f.write("--reset-params --out %s --label reset\n" % o("bt_c"))
        f.write("--set 'scale=1.5' --repeat 3 --render\n")
    run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + ["--batch", o("batch.txt"), "--report", o("batch.json")])
    d1 = maxdiff(load(o("bt_a.f32")), grad * np.array([2, 2, 2, 1], np.float32))
    d2 = maxdiff(load(o("bt_b.f32")), grad * np.array([1, 2, 2, 1], np.float32))
    d3 = maxdiff(load(o("bt_c.f32")), grad)
    rep = json.load(open(o("batch.json")))
    nrep = len(rep["jobs"][-1]["frames"][0]["renderMs"])
    check("batch: params persist across lines, reset works, repeat timing", max(d1, d2, d3) < 1e-6 and nrep == 3,
          "d=%.2g/%.2g/%.2g repeats=%d" % (d1, d2, d3, nrep))

    # ---- batch --keep-going: a failing job does not stop the rest; exit code reports it -------
    with open(o("batch_kg.txt"), "w") as f:
        f.write("--set scale=2 --out %s\n" % o("kg_a"))
        f.write("--set nosuch=1 --out %s\n" % o("kg_bad"))
        f.write("--set scale=3 --out %s\n" % o("kg_c"))
    p = run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + ["--batch", o("batch_kg.txt"), "--keep-going",
               "--report", o("batch_kg.json")], expect=2)
    rep = json.load(open(o("batch_kg.json")))
    d = maxdiff(load(o("kg_c.f32")), grad * np.array([3, 3, 3, 1], np.float32))
    jobs = {j["label"]: j for j in rep["jobs"]}
    check("batch --keep-going continues after a failed job",
          d < 1e-6 and jobs["line 2"]["error"] != "" and jobs["line 3"]["error"] == "", "exit %d" % p.returncode)
    os.remove(o("kg_c.f32"))
    p = run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + ["--batch", o("batch_kg.txt")], expect=2)
    check("batch stops at the first failed job by default", not os.path.exists(o("kg_c.f32")) and os.path.exists(o("kg_a.f32")))

    # ---- general context, notification modes, OpenCL device listing --------------------------
    run(host, [b("sdks_gpugain"), "--context", "general", "--in", "pattern:gradient"] + size + gain + ["--out", o("gg_general")])
    d = maxdiff(load(o("gg_general.f32")), grad * np.array([2, 1, 2, 0.75], np.float32))
    check("general context instance renders", d < 1e-6)
    run(host, [b("sdks_tester"), "--in", "pattern:gradient"] + size + ["--frames", "0:5", "--press", "analyseButton",
               "--plugin-edit-notify", "off", "--report", o("tester_off.json"), "--render"])
    log = json.load(open(o("tester_off.json")))["instanceChangedLog"]
    check("--plugin-edit-notify off suppresses pluginEdited notifications", not any("PluginEdited" in l for l in log), str(log))
    run(host, [b("sdks_tester"), "--in", "pattern:gradient"] + size + ["--frames", "0:5", "--press", "analyseButton",
               "--plugin-edit-notify", "deferred", "--report", o("tester_def.json"), "--render"])
    log = json.load(open(o("tester_def.json")))["instanceChangedLog"]
    check("--plugin-edit-notify deferred delivers them after the user edit", sum("PluginEdited" in l for l in log) >= 1 and
          log[0].startswith("OfxChangeUserEdited"), "%d entries" % len(log))
    if have_cl:
        p = run(host, ["--list-cl-devices"])
        check("--list-cl-devices", "platform 0 device 0" in p.stdout, p.stdout.strip().splitlines()[0][:70])

    # ---- PNG writer -----------------------------------------------------------------------------
    run(host, [b("sdks_gpugain"), "--in", o("rand_in.f32")] + size + ["--set", "scale=0.5", "--out", o("png8")])
    run(host, [b("sdks_gpugain"), "--in", o("rand_in.f32")] + size + ["--set", "scale=0.5", "--png16", "--png-alpha", "--out", o("png16")])
    f = load(o("png8.f32"))
    p8 = np.asarray(Image.open(o("png8.png")))
    e8 = quant(f[..., :3], 255).astype(np.uint8)
    check("PNG 8-bit RGB (Pillow) == quantised output", p8.shape == (H, W, 3) and np.array_equal(p8, e8))
    check("PNG 8-bit (independent zlib decoder) == quantised output", np.array_equal(decode_png(o("png8.png")), e8))
    f16 = load(o("png16.f32"))
    e16 = quant(f16, 65535).astype(np.uint16)
    d16 = decode_png(o("png16.png")).astype(np.uint16)
    check("PNG 16-bit RGBA (independent decoder) == quantised output", np.array_equal(d16, e16))
    Image.open(o("png16.png")).load()
    big = rng.uniform(0, 1, (300, 400, 4)).astype("<f4")
    big[:150] = 0.25  # long runs exercise LZ77 matches
    big.tofile(o("big_in.f32"))
    run(host, [b("sdks_invert"), "--in", o("big_in.f32"), "--width", "400", "--height", "300", "--out", o("png_big")])
    eb = quant(1.0 - big[..., :3], 255).astype(np.uint8)
    check("PNG deflate on 400x300 (runs + noise) decodes exactly", np.array_equal(decode_png(o("png_big.png")), eb),
          "%d bytes" % os.path.getsize(o("png_big.png")))

    # ---- error handling ------------------------------------------------------------------------
    p = run(host, [b("sdks_gpugain"), "--in", "pattern:gradient"] + size + ["--set", "nosuch=1", "--render"], expect=2)
    check("unknown parameter -> exit 2 with message", "unknown parameter 'nosuch'" in p.stderr)
    p = run(host, [o("does_not_exist.ofx.bundle"), "--list-params"], expect=3)
    check("missing bundle -> exit 3", p.returncode == 3)
    p = run(host, [b("sdks_gpugain"), "--in", o("rand_in.f32"), "--width", "10", "--height", "10", "--render"], expect=1)
    check("wrong .f32 size -> clean failure", "does not match" in p.stderr)

    # ---- protocol diagnostics: optional property gets returned kOfxStatErrUnknown, no crash ----
    rep = json.load(open(o("gg_clb.json" if have_cl else "gg_id.json")))
    check("report: unknown property gets recorded (ErrUnknown path)", isinstance(rep["unknownPropertyGets"], dict))
    check("report: suites fetched", any("OfxImageEffectSuite" in s for s in rep["suitesFetched"]))

    n_fail = sum(1 for r in RESULTS if not r[1])
    print("\n%d checks, %d failed" % (len(RESULTS), n_fail))
    return 1 if n_fail else 0


if __name__ == "__main__":
    sys.exit(main())
