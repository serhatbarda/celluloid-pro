"""Generate the C++ data includes from the reference data (single source of truth):

    python3 reference/gen_tables.py

  reference/data/*.csv     -> src/core/SpectralTables.inc   (CIE CMFs, D65, daylight basis)
  reference/stocks.json    -> src/core/StockData.inc        (designed stock library)

Run it after every edit of reference/stocks.json (tests/core checks that the C++ table and the
NumPy model agree through reference/golden/core_golden.txt, regenerated by reference/golden.py).
"""
import hashlib
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import spectral as sp  # noqa: E402

ROOT = os.path.dirname(sp.HERE)
OUT = os.path.join(ROOT, 'src', 'core')
MAXLOBES = 6


def fnum(x):
    x = float(x)
    if x == int(x) and abs(x) < 1e9:
        return f'{int(x)}.0'
    return repr(x)


def lobeset(lobes):
    lobes = lobes or []
    if len(lobes) > MAXLOBES:
        raise ValueError('too many lobes')
    items = ', '.join('{%s, %s, %s, %s}' % tuple(fnum(v) for v in l) for l in lobes)
    return '{%d, {%s}}' % (len(lobes), items if items else '{0.0, 1.0, 1.0, 0.0}')


def curve(c):
    return '{%s}' % ', '.join(fnum(c[k]) for k in ('fog', 'gamma', 'k', 'x0', 'R', 'p'))


def illum(s):
    t = {'blackbody': 0, 'daylight': 1, 'd65': 2}[s['type']]
    uv = s.get('uvcut', [-1, -1])
    ir = s.get('ircut', [-1, -1])
    return '{%d, %s, %s, %s, %s, %s, %s}' % (t, fnum(s.get('cct', 6504)), fnum(uv[0]), fnum(uv[1]),
                                            fnum(ir[0]), fnum(ir[1]), fnum(s.get('irdepth', 1.0)))


def base(b):
    return '{%s, %s, %s}' % (fnum(b.get('d0', 0.0)), fnum(b.get('blue', 0.0)), fnum(b.get('red', 0.0)))


def mat3(m):
    return '{' + ', '.join('{' + ', '.join(fnum(v) for v in row) + '}' for row in m) + '}'


def cstr(s):
    return json.dumps(s, ensure_ascii=True)


def neg_entry(n, scan_xover=0.0):
    kind = {'negative': 0, 'reversal': 1, 'bw': 2}[n['kind']]
    sens = n['sensitivity'] if kind != 2 else [n['sensitivity'][0]] * 3
    curves = n['curves'] if kind != 2 else [n['curves'][0]] * 3
    if len(curves) == 1:
        curves = curves * 3
    dyes = n.get('dyes', [{'primary': [], 'secondary': []}] * 3)
    gran = n['granularity'] if kind != 2 else [n['granularity'][0]] * 3
    inter = n.get('interlayer', [[0, 0, 0]] * 3)
    scanM = n.get('scanMatrix', [[1, 0, 0], [0, 1, 0], [0, 0, 1]])
    lines = [
        '{',
        f'  {cstr(n["name"])}, {cstr(n.get("description", ""))}, {kind}, {illum(n["balance"])},',
        f'  {fnum(n.get("grainSizeScale", 1))}, {fnum(n.get("halationScale", 1))}, {fnum(n.get("bloomScale", 1))},',
        '  {' + ', '.join(lobeset(s) for s in sens) + '},',
        '  {' + ', '.join(curve(c) for c in curves) + '},',
        '  {' + ', '.join('{%s, %s}' % (lobeset(d.get('primary')), lobeset(d.get('secondary'))) for d in dyes) + '},',
        '  {' + ', '.join(fnum(v) for v in n.get('mask', [0, 0, 0])) + '},',
        f'  {base(n.get("base", {"d0": 0.0}))}, {mat3(inter)},',
        '  {' + ', '.join(fnum(v) for v in gran) + '},',
        f'  {fnum(n.get("silver", 0.9))}, {1 if "silverSpectrum" in n else 0}, {lobeset(n.get("silverSpectrum"))},',
        f'  {fnum(n.get("greyY", 0.10))}, {mat3(scanM)}, {mat3(n.get("scanRoot", [[0, 0, 0]] * 3))}, {fnum(n.get("scanCrossover", scan_xover))}, {fnum(n.get("scanContrast", 1.0))},'
        f' {fnum(n.get("hueHold", 0.0))}, {fnum(n.get("chromaHold", 0.0))},',
        f'  {cstr(n.get("provenance", ""))}',
        '}',
    ]
    return '\n'.join(lines)


def print_entry(p):
    return '\n'.join([
        '{',
        f'  {cstr(p["name"])}, {cstr(p.get("description", ""))},',
        '  {' + ', '.join(lobeset(s) for s in p['sensitivity']) + '},',
        '  {' + ', '.join('{%s, %s}' % (lobeset(d.get('primary')), lobeset(d.get('secondary'))) for d in p['dyes']) + '},',
        '  {' + ', '.join(curve(c) for c in p['curves']) + '},',
        f'  {base(p["base"])}, {fnum(p["greyY"])}, {fnum(p.get("silver", 0.0))}, {fnum(p.get("silverDensity", 0.9))},',
        '  {' + ', '.join(fnum(v) for v in p.get('fade', [1.0, 1.0, 1.0])) + '},',
        f'  {fnum(p.get("hueHold", 0.0))}, {fnum(p.get("chromaHold", 0.0))}, {lobeset(p.get("monoTone"))},',
        f'  {cstr(p.get("provenance", ""))}',
        '}'])


def lab_entry(L):
    """v1.3 print lab model (stocks.json "lab")"""
    v3 = lambda a: '{' + ', '.join(fnum(x) for x in a) + '}'
    whites = '{' + ', '.join('{%d, %s, %s}' % (w['adapt'], fnum(w['x']), fnum(w['y'])) for w in L['whites']) + '}'
    return ('static const LabDef kLab = {%s, %s, %s, %s, %s, %s, {%s}, %s, %s, %s};\n' % (
        whites, v3(L['aimStep']), fnum(L['aimGamma']), fnum(L['aimDmax']), fnum(L['aimFog']), v3(L['aimLayer']),
        ', '.join(curve(c) for c in L['dupe']), v3(L['mpAim']), v3(L['dnAim']), fnum(L['telecineBlack'])))


def stock_hash(j):
    return hashlib.sha1(json.dumps(j, sort_keys=True).encode()).hexdigest()[:16]


def main():
    with open(os.path.join(OUT, 'SpectralTables.inc'), 'w') as f:
        f.write('// GENERATED by reference/gen_tables.py from reference/data/*.csv -- do not edit.\n')
        f.write('// CIE 1931 2 deg CMFs (CIE 015:2018), CIE D65 and daylight basis S0,S1,S2; 380..780 nm @ 5 nm.\n')
        f.write('static const double kCMF[81][3] = {\n')
        for r in sp.CMF:
            f.write('  {%s},\n' % ', '.join(repr(float(v)) for v in r))
        f.write('};\nstatic const double kD65[81] = {\n')
        f.write(',\n'.join('  ' + repr(float(v)) for v in sp.D65) + '\n};\n')
        f.write('static const double kDaylightBasis[81][3] = {\n')
        for r in sp.DAYLIGHT_BASIS:
            f.write('  {%s},\n' % ', '.join(repr(float(v)) for v in r))
        f.write('};\n')
    j = json.load(open(os.path.join(sp.HERE, 'stocks.json')))
    with open(os.path.join(OUT, 'StockData.inc'), 'w') as f:
        f.write('// GENERATED by reference/gen_tables.py from reference/stocks.json -- do not edit.\n')
        f.write('// Designed stock library (see docs/STOCKS.md). Edit stocks.json and regenerate.\n')
        f.write(f'#define CEL_STOCK_HASH "{stock_hash(j)}"\n')
        L = j['lamps']
        f.write(f'static const LampSet kLamps = {{{illum(L["printer"])}, {illum(L["projector"])}, {illum(L["scanner"])}}};\n')
        f.write(lab_entry(j['lab']))
        sc = j['scanner']
        cv = sc['curve']
        f.write('static const ScannerDef kScanner = {{%s}, %s, %s, %s, %s, %s, %s, %s};\n' % (
            ', '.join(lobeset(s) for s in sc['sensitivity']), fnum(cv['gamma']), fnum(cv['k']), fnum(cv['R']),
            fnum(cv['p']), fnum(sc['greyY']), fnum(sc.get('hueHold', 0.0)), fnum(sc.get('chromaHold', 0.0))))
        f.write(f'static const int kNumNegatives = {len(j["negatives"])};\n')
        f.write('static const NegDef kNegatives[] = {\n')
        f.write(',\n'.join(neg_entry(n, j['scanner'].get('crossover', 0.0)) for n in j['negatives']))
        f.write('\n};\n')
        f.write(f'static const int kNumPrints = {len(j["prints"])};\n')
        f.write('static const PrintDef kPrints[] = {\n')
        f.write(',\n'.join(print_entry(p) for p in j['prints']))
        f.write('\n};\n')
    print('wrote SpectralTables.inc, StockData.inc (stock hash %s)' % stock_hash(j))


if __name__ == '__main__':
    main()
